import type {
  ChannelSummary,
  Comment,
  VideoDetail as GatewayVideoDetail,
  Image,
  Storyboard,
  VideoSummary,
} from "@owntube/contracts/model";
import type {
  CaptionTrack,
  UnifiedChannel,
  UnifiedComment,
  UnifiedVideo,
  VideoDetail,
  VideoPlayback,
  VideoStoryboard,
} from "@/server/catalog/types";

/**
 * The gateway's model, flattened into what the web UI shows: one image per
 * slot, seconds for dates, plain numbers for counts.
 */

/** The largest image (YouTube lists them smallest first, but do not rely on it). */
export function largestImage(images: readonly Image[]): string | undefined {
  let best: Image | undefined;
  for (const image of images) {
    if (!best || (image.width ?? 0) > (best.width ?? 0)) best = image;
  }
  return best?.url;
}

function seconds(ms: number | undefined): number | undefined {
  return ms === undefined ? undefined : Math.floor(ms / 1000);
}

export function toUnifiedVideo(v: VideoSummary): UnifiedVideo {
  const live = v.live === "live";
  return {
    videoId: v.videoId,
    title: v.title,
    channelId: v.channel?.channelId,
    channelName: v.channel?.name,
    channelAvatarUrl: v.channel ? largestImage(v.channel.avatars) : undefined,
    thumbnailUrl: largestImage(v.thumbnails),
    durationSeconds: live ? undefined : v.durationSec,
    viewCount: v.views?.value,
    publishedText: v.published?.text,
    publishedAt: seconds(v.published?.at ?? v.startsAt),
    isLive: live || undefined,
    isUpcoming: v.live === "upcoming" || undefined,
    isShort: v.isShort,
  };
}

export function toUnifiedChannel(c: ChannelSummary): UnifiedChannel {
  return {
    channelId: c.channelId,
    name: c.name,
    avatarUrl: largestImage(c.avatars),
    subscriberCount: c.subscribers?.value,
    description: c.description,
  };
}

export function toUnifiedComment(c: Comment): UnifiedComment {
  return {
    commentId: c.commentId,
    author: c.author.name,
    authorId: c.author.channelId,
    authorAvatarUrl: largestImage(c.author.avatars),
    text: c.text,
    publishedText: c.publishedText,
    likeCount: c.likes?.value,
    replyCount: c.replyCount,
    isPinned: c.isPinned || undefined,
    isVerified: c.byChannelOwner || undefined,
  };
}

/** Only VOD storyboards: a live one grows while it plays and the scrubber has no use for it yet. */
function toStoryboard(s: Storyboard | undefined): VideoStoryboard | undefined {
  if (s?.kind !== "vod") return undefined;
  return {
    templateUrl: s.templateUrl,
    thumbWidth: s.thumbWidth,
    thumbHeight: s.thumbHeight,
    count: s.thumbCount,
    intervalMs: s.intervalMs,
    columns: s.columns,
    rows: s.rows,
    storyboardCount: s.sheetCount,
  };
}

/** Signed playback, plus a signer for caption URLs (same expiry). */
export type SignedPlayback = {
  playback: VideoPlayback;
  captions: (languageCode: string, autoGenerated: boolean) => string;
};

export function toVideoDetail(
  d: GatewayVideoDetail,
  signed: SignedPlayback | undefined,
): VideoDetail {
  const summary = toUnifiedVideo(d);
  const captions: CaptionTrack[] = d.captions.map((c) => ({
    label: c.label,
    languageCode: c.languageCode,
    autoGenerated: c.autoGenerated,
    ...(signed
      ? { src: signed.captions(c.languageCode, c.autoGenerated) }
      : {}),
  }));
  return {
    videoId: d.videoId,
    title: d.title,
    description: d.description,
    channelId: summary.channelId,
    channelName: summary.channelName,
    channelAvatarUrl: summary.channelAvatarUrl,
    channelSubscriberCount: d.channel?.subscribers?.value,
    relatedVideos: d.related.map(toUnifiedVideo),
    storyboard: toStoryboard(d.storyboard),
    thumbnailUrl: summary.thumbnailUrl,
    durationSeconds: summary.durationSeconds,
    viewCount: summary.viewCount,
    likeCount: d.likes?.value,
    publishedText: summary.publishedText,
    publishedAt: summary.publishedAt,
    isLive: summary.isLive,
    isPostLiveDvr: d.live === "post-live" || undefined,
    isUpcoming: summary.isUpcoming,
    isShort: d.isShort,
    ...(d.originalLanguage ? { originalLanguage: d.originalLanguage } : {}),
    audioLanguages: d.audioLanguages,
    qualities: d.qualities,
    captions,
    ...(signed ? { playback: signed.playback } : {}),
  };
}
