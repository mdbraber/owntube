import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { appRouter } from "@/server/trpc/root";
import { createTestDb } from "@/test/db";

const ID = "dQw4w9WgXcQ";

/** A gateway video page (`@owntube/contracts` VideoDetail). */
function gatewayVideo(overrides: Record<string, unknown> = {}) {
  return {
    videoId: ID,
    title: "Title",
    channel: {
      channelId: "UCuAXFkgsw1L7xaCfnd5JJOw",
      name: "Channel",
      avatars: [
        { url: "/media/img/yt3/a=s48", width: 48, height: 48 },
        { url: "/media/img/yt3/a=s176", width: 176, height: 176 },
      ],
      subscribers: { value: 1200, approximate: true },
    },
    thumbnails: [{ url: "/media/img/yti/vi/x/hqdefault.jpg", width: 480 }],
    durationSec: 212,
    views: { value: 1000, approximate: false },
    published: { at: 1_256_428_800_000, precision: "exact" },
    live: "none",
    isShort: false,
    description: "d",
    keywords: [],
    captions: [{ languageCode: "en", label: "English", autoGenerated: true }],
    chapters: [],
    related: [],
    unplayable: null,
    ...overrides,
  };
}

function answer(body: unknown, status = 200) {
  vi.mocked(fetch).mockResolvedValueOnce(
    new Response(JSON.stringify(body), {
      status,
      headers: { "content-type": "application/json" },
    }),
  );
}

describe("videoRouter", () => {
  beforeEach(() => {
    vi.stubGlobal(
      "fetch",
      vi.fn(() => Promise.reject(new Error("fetch not mocked for this test"))),
    );
  });

  afterEach(() => {
    vi.unstubAllGlobals();
  });

  it("answers a video page with signed gateway playback", async () => {
    const { db, sqlite } = createTestDb();
    answer(gatewayVideo());
    const caller = appRouter.createCaller({ db, userId: null });
    const detail = await caller.video.detail({ videoId: ID });
    expect(detail).toMatchObject({
      title: "Title",
      channelName: "Channel",
      channelAvatarUrl: "/media/img/yt3/a=s176",
      durationSeconds: 212,
      publishedAt: 1_256_428_800,
    });
    expect(detail.playback?.hls).toMatch(
      new RegExp(`^/media/v/${ID}/master\\.m3u8\\?exp=\\d+&sig=`),
    );
    expect(detail.playback?.dash).toMatch(/manifest\.mpd\?exp=/);
    expect(detail.captions?.[0]?.src).toMatch(
      new RegExp(`^/media/v/${ID}/captions\\.vtt\\?lang=en&auto=1&exp=`),
    );
    expect(vi.mocked(fetch).mock.calls[0]?.[0]).toBe(
      `http://gateway.invalid/api/video/${ID}`,
    );
    sqlite.close();
  });

  it("turns YouTube's refusal into a typed error", async () => {
    const { db, sqlite } = createTestDb();
    answer(
      gatewayVideo({
        unplayable: { kind: "unavailable", reason: "This video is private" },
      }),
    );
    const caller = appRouter.createCaller({ db, userId: null });
    await expect(caller.video.detail({ videoId: ID })).rejects.toMatchObject({
      code: "NOT_FOUND",
      message: "This video is private",
    });
    sqlite.close();
  });

  it("answers comments", async () => {
    const { db, sqlite } = createTestDb();
    answer({
      comments: [
        {
          commentId: "x",
          author: { name: "Viewer", avatars: [] },
          text: "Hello",
          publishedText: "now",
          isPinned: false,
          byChannelOwner: false,
        },
      ],
      count: { value: 1, approximate: false },
    });
    const caller = appRouter.createCaller({ db, userId: null });
    const comments = await caller.video.comments({
      videoId: ID,
      sortBy: "top",
    });
    expect(comments.comments).toHaveLength(1);
    expect(comments.comments[0]?.text).toBe("Hello");
    expect(comments.commentCount).toBe(1);
    sqlite.close();
  });
});
