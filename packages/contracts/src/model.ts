import { z } from "zod";

/**
 * OwnTube's model of YouTube's catalogue, as the gateway serves it. Every
 * field is YouTube's data or derived from it deterministically; where YouTube
 * only gives approximate data (list rows: "1.2M views", "2 weeks ago") the
 * model says so instead of guessing. Image URLs point at the gateway's image
 * route, never at Google.
 */

export const imageSchema = z.object({
  url: z.string(),
  width: z.number().int().optional(),
  height: z.number().int().optional(),
});
export type Image = z.infer<typeof imageSchema>;

export const channelRefSchema = z.object({
  channelId: z.string(),
  name: z.string(),
  avatars: z.array(imageSchema),
});
export type ChannelRef = z.infer<typeof channelRefSchema>;

/** A count YouTube gave exactly, or only as abbreviated text ("1.2M"). */
export const countSchema = z.object({
  value: z.number().int().nonnegative(),
  approximate: z.boolean(),
});
export type Count = z.infer<typeof countSchema>;

/** When a video was published: an exact instant where YouTube gives one, else its relative text. */
export const publishedSchema = z.object({
  /** Epoch milliseconds, at `precision` (list rows only carry `text`). */
  at: z.number().optional(),
  /** "exact" when YouTube gave an instant; "day" when only a date ("Oct 25, 2009", read as UTC midnight). */
  precision: z.enum(["exact", "day"]).optional(),
  /** YouTube's own wording, e.g. "2 weeks ago" or "Oct 25, 2009". */
  text: z.string().optional(),
});
export type Published = z.infer<typeof publishedSchema>;

export const liveStateSchema = z.enum([
  "none",
  "live",
  "upcoming",
  "post-live",
]);
export type LiveState = z.infer<typeof liveStateSchema>;

/** A video as it appears in a list (search, channel, related, playlist, feed). */
export const videoSummarySchema = z.object({
  videoId: z.string(),
  title: z.string(),
  /** The first credited channel. */
  channel: channelRefSchema.optional(),
  /** Every credited channel, for collaborations (the first is `channel`). */
  collaborators: z.array(channelRefSchema).optional(),
  thumbnails: z.array(imageSchema),
  durationSec: z.number().int().nonnegative().optional(),
  views: countSchema.optional(),
  published: publishedSchema.optional(),
  live: liveStateSchema,
  /** Start of an upcoming stream or premiere, epoch milliseconds. */
  startsAt: z.number().optional(),
  isShort: z.boolean(),
  membersOnly: z.boolean().optional(),
});
export type VideoSummary = z.infer<typeof videoSummarySchema>;

export const channelSummarySchema = channelRefSchema.extend({
  handle: z.string().optional(),
  subscribers: countSchema.optional(),
  description: z.string().optional(),
});
export type ChannelSummary = z.infer<typeof channelSummarySchema>;

export const playlistSummarySchema = z.object({
  playlistId: z.string(),
  title: z.string(),
  thumbnails: z.array(imageSchema),
  videoCount: z.number().int().nonnegative().optional(),
  channel: channelRefSchema.optional(),
});
export type PlaylistSummary = z.infer<typeof playlistSummarySchema>;

export const captionTrackSchema = z.object({
  languageCode: z.string(),
  label: z.string(),
  autoGenerated: z.boolean(),
});
export type CaptionTrack = z.infer<typeof captionTrackSchema>;

/**
 * Seek-preview sprite sheets. `templateUrl` contains `$M` for the sheet number.
 * A VOD storyboard is a fixed set of sheets; a live one keeps growing (each
 * sheet number a later stretch of the stream), so it has no count or interval.
 */
export const storyboardSchema = z.discriminatedUnion("kind", [
  z.object({
    kind: z.literal("vod"),
    templateUrl: z.string(),
    thumbWidth: z.number().int().positive(),
    thumbHeight: z.number().int().positive(),
    thumbCount: z.number().int().positive(),
    intervalMs: z.number().int().positive(),
    columns: z.number().int().positive(),
    rows: z.number().int().positive(),
    sheetCount: z.number().int().positive(),
  }),
  z.object({
    kind: z.literal("live"),
    templateUrl: z.string(),
    thumbWidth: z.number().int().positive(),
    thumbHeight: z.number().int().positive(),
    columns: z.number().int().positive(),
    rows: z.number().int().positive(),
  }),
]);
export type Storyboard = z.infer<typeof storyboardSchema>;

export const chapterSchema = z.object({
  title: z.string(),
  startSec: z.number().nonnegative(),
  thumbnails: z.array(imageSchema),
});
export type Chapter = z.infer<typeof chapterSchema>;

export const unplayableSchema = z.object({
  kind: z.enum([
    "login-required",
    "bot-check",
    "age-restricted",
    "members-only",
    "upcoming",
    "unavailable",
    "unplayable",
  ]),
  reason: z.string(),
});

export const videoDetailSchema = videoSummarySchema.extend({
  channel: channelSummarySchema.optional(),
  description: z.string(),
  keywords: z.array(z.string()),
  category: z.string().optional(),
  likes: countSchema.optional(),
  captions: z.array(captionTrackSchema),
  storyboard: storyboardSchema.optional(),
  chapters: z.array(chapterSchema),
  related: z.array(videoSummarySchema),
  /** Why YouTube will not play it; null when it will. */
  unplayable: unplayableSchema.nullable(),
});
export type VideoDetail = z.infer<typeof videoDetailSchema>;

/** An opaque token for the next page of a list. */
export const continuationSchema = z.string().max(16_384);

export const channelTabSchema = z.enum([
  "videos",
  "shorts",
  "streams",
  "playlists",
]);
export type ChannelTab = z.infer<typeof channelTabSchema>;

export const channelDetailSchema = channelSummarySchema.extend({
  banners: z.array(imageSchema),
  videoCount: countSchema.optional(),
  links: z.array(z.object({ title: z.string(), url: z.string() })),
  /** Channels this one features on its home tab. */
  featuredChannels: z.array(channelSummarySchema),
  tabs: z.array(channelTabSchema),
});
export type ChannelDetail = z.infer<typeof channelDetailSchema>;

export const channelPageSchema = z.object({
  channel: channelDetailSchema.optional(),
  videos: z.array(videoSummarySchema),
  playlists: z.array(playlistSummarySchema),
  continuation: continuationSchema.optional(),
});
export type ChannelPage = z.infer<typeof channelPageSchema>;

/** Search's upload-date filter (YouTube's own windows). */
export const uploadDateSchema = z.enum(["today", "week", "month", "year"]);
export type UploadDate = z.infer<typeof uploadDateSchema>;

export const searchResultSchema = z.object({
  videos: z.array(videoSummarySchema),
  channels: z.array(channelSummarySchema),
  playlists: z.array(playlistSummarySchema),
  continuation: continuationSchema.optional(),
});
export type SearchResult = z.infer<typeof searchResultSchema>;

export const commentSchema = z.object({
  commentId: z.string(),
  author: z.object({
    channelId: z.string().optional(),
    name: z.string(),
    avatars: z.array(imageSchema),
  }),
  text: z.string(),
  publishedText: z.string().optional(),
  likes: countSchema.optional(),
  replyCount: z.number().int().nonnegative().optional(),
  isPinned: z.boolean(),
  byChannelOwner: z.boolean(),
});
export type Comment = z.infer<typeof commentSchema>;

export const commentPageSchema = z.object({
  comments: z.array(commentSchema),
  count: countSchema.optional(),
  continuation: continuationSchema.optional(),
});
export type CommentPage = z.infer<typeof commentPageSchema>;

export const playlistPageSchema = z.object({
  playlist: playlistSummarySchema.optional(),
  videos: z.array(videoSummarySchema),
  continuation: continuationSchema.optional(),
});
export type PlaylistPage = z.infer<typeof playlistPageSchema>;
