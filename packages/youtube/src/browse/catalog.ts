import type {
  ChannelDetail,
  ChannelPage,
  ChannelTab,
  Comment,
  CommentPage,
  PlaylistPage,
  SearchResult,
  Storyboard,
  UploadDate,
  VideoDetail,
} from "@owntube/contracts/model";
import { type Innertube, YT, YTNodes } from "youtubei.js";
import type { Unplayable } from "../playability.ts";
import type { RawPlayerResponse } from "../player.ts";
import { toImages } from "./images.ts";
import { collaboratorsFrom, collectItems, findContinuation } from "./items.ts";
import { parseCount } from "./text.ts";

/** YouTube's "Live" destination channel: what OwnTube calls Live (Invidious served it as "trending"). */
export const LIVE_CHANNEL = "UC4R8DWoMoI7CAwX8_LjQHig";

const TAB_NAMES: Record<string, ChannelTab> = {
  Videos: "videos",
  Shorts: "shorts",
  Live: "streams",
  Playlists: "playlists",
};

/**
 * OwnTube's catalogue of YouTube: video pages, channels, search, comments,
 * playlists and the Live page, mapped into `@owntube/contracts`. First pages
 * use youtubei.js's calls; later pages are fetched statelessly from the
 * continuation token alone, so any gateway instance can serve them.
 */
/** A video's player response, as OwnTube's own client identity asks for it (production: `YouTube.player`). */
export type PlayerSource = (
  videoId: string,
) => Promise<{ raw: RawPlayerResponse; unplayable: Unplayable | null }>;

export class Catalog {
  readonly #yt: () => Promise<Innertube>;
  readonly #player: PlayerSource;

  /**
   * `yt` supplies the youtubei.js instance for page data (in production the
   * current YouTube session's); `player` the player response, which comes
   * from OwnTube's own identity because youtubei.js's built-in ones draw bot
   * checks where it does not (seen 2026-11-26).
   */
  constructor(options: { yt: () => Promise<Innertube>; player: PlayerSource }) {
    this.#yt = options.yt;
    this.#player = options.player;
  }

  async video(videoId: string): Promise<VideoDetail> {
    const yt = await this.#yt();
    const [player, next, web] = await Promise.all([
      this.#player(videoId),
      yt.actions.execute("/next", {
        videoId,
        racyCheckOk: true,
        contentCheckOk: true,
      }),
      // Only for the microformat: WEB's player response carries the exact publish
      // time (and a stream's start) even when it will not play without a token.
      yt
        .getBasicInfo(videoId, { client: "WEB" })
        .catch(() => undefined),
    ]);
    // youtubei.js's own page model, over our player response and its page data.
    const info = new YT.VideoInfo(
      [{ success: true, status_code: 200, data: player.raw as never }, next],
      yt.actions,
      "",
    );
    const b = info.basic_info;
    const owner = (
      info.secondary_info as YTNodes.VideoSecondaryInfo | undefined
    )?.owner;
    const primary = info.primary_info as YTNodes.VideoPrimaryInfo | undefined;
    const subscribers = parseCount(owner?.subscriber_count?.toString());
    const channelId = b.channel_id ?? owner?.author.id;
    const channelName = b.author ?? owner?.author.name;
    const collaborators = collaboratorsFrom(owner?.author.endpoint);
    const live = b.is_live
      ? "live"
      : b.is_upcoming
        ? "upcoming"
        : b.is_post_live_dvr
          ? "post-live"
          : "none";
    const published = publishedOf(
      web?.basic_info.publish_date ?? b.publish_date,
      primary?.published?.toString(),
    );
    const start = web?.basic_info.start_timestamp ?? b.start_timestamp;
    const startsAt = start ? new Date(start).getTime() : undefined;
    const unplayable = player.unplayable;
    const related = collectItems(info.watch_next_feed ?? []).videos;
    // Dubbed videos name their tracks; the original one is the default.
    const originalLanguage = player.raw.streamingData?.adaptiveFormats
      ?.find((f) => f.audioTrack?.audioIsDefault)
      ?.audioTrack?.id.split(".")[0];
    const captions = (
      (info.captions as YTNodes.PlayerCaptionsTracklist | undefined)
        ?.caption_tracks ?? []
    ).map((t) => ({
      languageCode: t.language_code,
      label: t.name.toString(),
      autoGenerated: t.kind === "asr",
    }));
    return {
      videoId,
      title: b.title ?? primary?.title?.toString() ?? "",
      // A collaboration credits its channels in a dialog; the first is the video's channel.
      ...(collaborators[0]
        ? { channel: collaborators[0] }
        : channelId && channelName
          ? {
              channel: {
                channelId,
                name: channelName,
                avatars: toImages(owner?.author.thumbnails),
                ...(subscribers ? { subscribers } : {}),
              },
            }
          : {}),
      ...(collaborators.length > 1 ? { collaborators } : {}),
      thumbnails: toImages(b.thumbnail),
      ...(b.duration && live === "none" ? { durationSec: b.duration } : {}),
      ...(b.view_count !== undefined
        ? { views: { value: b.view_count, approximate: false } }
        : {}),
      ...(published ? { published } : {}),
      live,
      ...(startsAt && live === "upcoming" ? { startsAt } : {}),
      isShort: false,
      ...(unplayable?.kind === "members-only" ? { membersOnly: true } : {}),
      description: b.short_description ?? "",
      keywords: b.keywords ?? [],
      ...(b.category ? { category: b.category } : {}),
      ...(b.like_count !== undefined
        ? { likes: { value: b.like_count, approximate: false } }
        : {}),
      captions,
      ...(originalLanguage ? { originalLanguage } : {}),
      ...storyboardOf(info.storyboards),
      chapters: chaptersOf(info.player_overlays),
      related,
      unplayable: unplayable
        ? { kind: unplayable.kind, reason: unplayable.reason }
        : null,
    };
  }

  async channel(
    channelId: string,
    tab: ChannelTab,
    continuation?: string,
  ): Promise<ChannelPage> {
    const yt = await this.#yt();
    if (continuation)
      return {
        ...listPage(await this.#continue(yt, "/browse", continuation)),
        channel: undefined,
      };
    const ch = await yt.getChannel(channelId);
    // A channel need not have every tab (a music or Shorts-only channel has no Videos tab):
    // a missing one is an empty page, not an error.
    const tabName = {
      videos: "Videos",
      shorts: "Shorts",
      streams: "Live",
      playlists: "Playlists",
    }[tab];
    const has = ch.tabs.includes(tabName);
    const [tabbed, about] = await Promise.all([
      !has
        ? undefined
        : tab === "videos"
          ? ch.getVideos()
          : tab === "shorts"
            ? ch.getShorts()
            : tab === "streams"
              ? ch.getLiveStreams()
              : ch.getPlaylists(),
      ch.getAbout().catch(() => undefined),
    ]);
    const page = tabbed
      ? listPage(tabbed.current_tab)
      : { videos: [], playlists: [] };
    const channel = channelDetail(
      ch,
      collectItems(ch.current_tab).channels,
      about,
    );
    // A channel's own tabs leave the channel off each video; it is this one.
    const ref = {
      channelId: channel.channelId,
      name: channel.name,
      avatars: channel.avatars,
    };
    return {
      ...page,
      videos: page.videos.map((v) => (v.channel ? v : { ...v, channel: ref })),
      channel,
    };
  }

  /** `uploadDate` narrows to recent uploads; a continuation carries its query's filters. */
  async search(
    query: string,
    options: { uploadDate?: UploadDate; continuation?: string } = {},
  ): Promise<SearchResult> {
    const yt = await this.#yt();
    const { uploadDate, continuation } = options;
    const root = continuation
      ? await this.#continue(yt, "/search", continuation)
      : (
          await yt.search(
            query,
            uploadDate ? { upload_date: uploadDate } : undefined,
          )
        ).page;
    const items = collectItems(root);
    const next = findContinuation(root);
    return { ...items, ...(next ? { continuation: next } : {}) };
  }

  async suggestions(query: string): Promise<string[]> {
    return (await this.#yt()).getSearchSuggestions(query);
  }

  async comments(
    videoId: string,
    sort: "top" | "new",
    continuation?: string,
  ): Promise<CommentPage> {
    const yt = await this.#yt();
    const root = continuation
      ? await this.#continue(yt, "/next", continuation)
      : (
          await yt.getComments(
            videoId,
            sort === "new" ? "NEWEST_FIRST" : "TOP_COMMENTS",
          )
        ).page;
    const comments = collectComments(root);
    const next = findContinuation(root);
    return { comments, ...(next ? { continuation: next } : {}) };
  }

  async playlist(
    playlistId: string,
    continuation?: string,
  ): Promise<PlaylistPage> {
    const yt = await this.#yt();
    if (continuation)
      return listPage(await this.#continue(yt, "/browse", continuation));
    const p = await yt.getPlaylist(playlistId);
    const page = listPage(p.page);
    const count = parseCount(p.info.total_items);
    const channel =
      p.info.author?.id && p.info.author.name
        ? {
            channelId: p.info.author.id,
            name: p.info.author.name,
            avatars: toImages(p.info.author.thumbnails),
          }
        : undefined;
    return {
      ...page,
      playlist: {
        playlistId,
        title: p.info.title ?? "",
        thumbnails: toImages(p.info.thumbnails),
        ...(count ? { videoCount: count.value } : {}),
        ...(channel ? { channel } : {}),
      },
    };
  }

  /** YouTube's Live page: what is live now and coming up. */
  async live(): Promise<{ videos: VideoDetail["related"] }> {
    const ch = await (await this.#yt()).getChannel(LIVE_CHANNEL);
    return { videos: collectItems(ch.current_tab).videos };
  }

  /** A channel id for a URL or @handle. */
  async resolveChannel(urlOrHandle: string): Promise<string | undefined> {
    const url = urlOrHandle.startsWith("@")
      ? `https://www.youtube.com/${urlOrHandle}`
      : urlOrHandle;
    const endpoint = await (await this.#yt()).resolveURL(url);
    const id = (endpoint.payload as { browseId?: string } | undefined)
      ?.browseId;
    return id?.startsWith("UC") ? id : undefined;
  }

  /** The next page of a list, from its continuation token alone. */
  async #continue(
    yt: Innertube,
    endpoint: "/browse" | "/search" | "/next",
    token: string,
  ): Promise<unknown> {
    return yt.actions.execute(endpoint, { continuation: token, parse: true });
  }
}

function listPage(root: unknown): {
  videos: ChannelPage["videos"];
  playlists: ChannelPage["playlists"];
  continuation?: string;
} {
  const items = collectItems(root);
  const next = findContinuation(root);
  return {
    videos: items.videos,
    playlists: items.playlists,
    ...(next ? { continuation: next } : {}),
  };
}

function channelDetail(
  ch: Awaited<ReturnType<Innertube["getChannel"]>>,
  featured: ChannelDetail["featuredChannels"],
  about: unknown,
): ChannelDetail {
  const header = ch.header as YTNodes.PageHeader | undefined;
  const rows = header?.content?.metadata?.metadata_rows ?? [];
  const parts = rows.flatMap(
    (r) => r.metadata_parts?.map((p) => p.text?.toString() ?? "") ?? [],
  );
  const handle = parts.find((p) => p.startsWith("@"));
  // The About panel is more precise ("8,013 videos") than the header ("8K videos").
  const meta =
    about instanceof YTNodes.AboutChannel ? about.metadata : undefined;
  const subscribers =
    parseCount(meta?.subscriber_count?.toString()) ??
    parseCount(parts.find((p) => /subscriber/i.test(p)));
  const videoCount =
    parseCount(meta?.video_count?.toString()) ??
    parseCount(parts.find((p) => /\bvideos?\b/i.test(p)));
  const links = (meta?.links ?? [])
    .filter(
      (l): l is YTNodes.ChannelExternalLinkView =>
        l instanceof YTNodes.ChannelExternalLinkView,
    )
    .map(linkOf)
    .filter((l): l is { title: string; url: string } => Boolean(l));
  const banners = (
    header?.content?.banner as unknown as
      | { image?: Array<{ url: string; width?: number; height?: number }> }
      | undefined
  )?.image;
  const tabs = ch.tabs
    .map((t) => TAB_NAMES[t])
    .filter((t): t is ChannelTab => Boolean(t));
  return {
    channelId: ch.metadata.external_id ?? "",
    name: ch.metadata.title ?? "",
    avatars: toImages(ch.metadata.avatar),
    ...(handle ? { handle } : {}),
    ...(subscribers ? { subscribers } : {}),
    // The header's description is cut at 160 characters; the About panel has all of it.
    ...((meta?.description?.toString() ?? ch.metadata.description)
      ? {
          description: meta?.description?.toString() ?? ch.metadata.description,
        }
      : {}),
    banners: toImages(banners),
    ...(videoCount ? { videoCount } : {}),
    links,
    featuredChannels: featured,
    tabs,
  };
}

/** An exact instant from the microformat when present, else the page's own date ("Oct 25, 2009"), at day precision. */
function publishedOf(
  exact: string | null | undefined,
  text: string | undefined,
): VideoDetail["published"] {
  const at = Date.parse(exact ?? "");
  if (Number.isFinite(at))
    return { at, precision: "exact", ...(text ? { text } : {}) };
  const day = /([A-Z][a-z]{2} \d{1,2}, \d{4})/.exec(text ?? "")?.[1];
  const dayAt = day ? Date.parse(`${day} 00:00:00 UTC`) : Number.NaN;
  if (Number.isFinite(dayAt))
    return { at: dayAt, precision: "day", ...(text ? { text } : {}) };
  return text ? { text } : undefined;
}

/** Chapters from the player bar's markers (the description's, or YouTube's automatic ones). */
function chaptersOf(overlays: unknown): VideoDetail["chapters"] {
  const bar = (
    overlays as { decorated_player_bar?: { player_bar?: unknown } } | undefined
  )?.decorated_player_bar?.player_bar;
  if (!(bar instanceof YTNodes.MultiMarkersPlayerBar)) return [];
  const marker =
    bar.markers_map.find((m) => m.marker_key === "DESCRIPTION_CHAPTERS") ??
    bar.markers_map.find((m) => /CHAPTERS/.test(m.marker_key));
  return (marker?.value.chapters ?? []).map((c) => ({
    title: c.title.toString(),
    startSec: c.time_range_start_millis / 1000,
    thumbnails: toImages(c.thumbnail),
  }));
}

/** An external link of a channel's About panel: YouTube wraps the URL in its redirector. */
function linkOf(
  view: YTNodes.ChannelExternalLinkView,
): { title: string; url: string } | undefined {
  const text = view.link.toString();
  const endpointUrl = (
    view.link.runs?.[0] as
      | { endpoint?: { payload?: { url?: string } } }
      | undefined
  )?.endpoint?.payload?.url;
  let url = endpointUrl ?? "";
  try {
    const u = new URL(url, "https://www.youtube.com");
    url =
      u.pathname === "/redirect"
        ? (u.searchParams.get("q") ?? "")
        : u.toString();
  } catch {
    url = "";
  }
  if (!url && text) url = /^https?:\/\//.test(text) ? text : `https://${text}`;
  return url ? { title: view.title.toString() || text, url } : undefined;
}

function storyboardOf(storyboards: unknown): { storyboard?: Storyboard } {
  if (storyboards instanceof YTNodes.PlayerLiveStoryboardSpec) {
    const board = storyboards.board;
    const templateUrl = toImages([{ url: board.template_url }])[0]?.url;
    if (!templateUrl) return {};
    return {
      storyboard: {
        kind: "live",
        templateUrl,
        thumbWidth: board.thumbnail_width,
        thumbHeight: board.thumbnail_height,
        columns: board.columns,
        rows: board.rows,
      },
    };
  }
  if (!(storyboards instanceof YTNodes.PlayerStoryboardSpec)) return {};
  // The last board has the largest thumbnails.
  const board = storyboards.boards[storyboards.boards.length - 1];
  const templateUrl = board && toImages([{ url: board.template_url }])[0]?.url;
  if (!board || !templateUrl) return {};
  return {
    storyboard: {
      kind: "vod",
      templateUrl,
      thumbWidth: board.thumbnail_width,
      thumbHeight: board.thumbnail_height,
      thumbCount: board.thumbnail_count,
      intervalMs: board.interval,
      columns: board.columns,
      rows: board.rows,
      sheetCount: board.storyboard_count,
    },
  };
}

function collectComments(root: unknown): Comment[] {
  const out: Comment[] = [];
  const stack: unknown[] = [root];
  const visited = new Set<unknown>();
  while (stack.length > 0) {
    const node = stack.pop();
    if (!node || typeof node !== "object" || visited.has(node)) continue;
    visited.add(node);
    if (node instanceof YTNodes.CommentThread && node.comment) {
      const c = node.comment;
      const likes = parseCount(c.like_count);
      const replies = parseCount(c.reply_count);
      out.push({
        commentId: c.comment_id,
        author: {
          ...(c.author?.id ? { channelId: c.author.id } : {}),
          name: c.author?.name ?? "",
          avatars: toImages(c.author?.thumbnails),
        },
        text: c.content?.toString() ?? "",
        ...(c.published_time ? { publishedText: c.published_time } : {}),
        ...(likes ? { likes } : {}),
        ...(replies ? { replyCount: replies.value } : {}),
        isPinned: c.is_pinned,
        byChannelOwner: c.author_is_channel_owner ?? false,
      });
      continue;
    }
    const children = Array.isArray(node)
      ? node
      : node instanceof Map
        ? [...node.values()]
        : Object.values(node);
    for (let i = children.length - 1; i >= 0; i--) {
      const child = children[i];
      if (child && typeof child === "object") stack.push(child);
    }
  }
  return out;
}
