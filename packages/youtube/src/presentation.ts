import type {
  AudioTrack,
  CaptionTrack,
  Presentation,
  VideoFamily,
  VideoTrack,
} from "@owntube/playback/tracks";
import type { PlayerResult, RawFormat } from "./player.ts";

/** Where each track of a presentation is fetched from. */
export interface PresentationSources {
  presentation: Presentation;
  /** Track id → stream URL (and its size, for answering ranges). */
  media: Map<string, { url: string; contentLength: number; itag: number }>;
  /** Caption id → timedtext URL. */
  captions: Map<string, string>;
}

const HDR_TRANSFERS = new Set([
  "COLOR_TRANSFER_CHARACTERISTICS_SMPTEST2084",
  "COLOR_TRANSFER_CHARACTERISTICS_ARIB_STD_B67",
]);

/**
 * The byte-range presentation of a player response: every adaptive format
 * with a URL and an index becomes a track. HDR is left out (players are not
 * asked about HDR support yet) and so are DRC audio duplicates.
 */
export function toPresentation(result: PlayerResult): PresentationSources {
  const media: PresentationSources["media"] = new Map();
  const video: VideoTrack[] = [];
  const audio: AudioTrack[] = [];
  for (const format of result.formats) {
    const parsed = parseMime(format.mimeType);
    const contentLength = Number(format.contentLength);
    if (
      !parsed ||
      !format.initRange ||
      !format.indexRange ||
      !(contentLength > 0)
    )
      continue;
    const base = {
      codecs: parsed.codecs,
      bitrate: format.bitrate ?? 0,
      contentLength,
      init: range(format.initRange),
      index: range(format.indexRange),
    };
    if (parsed.kind === "video") {
      const family = familyOf(parsed.codecs);
      if (!family || !format.width || !format.height) continue;
      if (HDR_TRANSFERS.has(format.colorInfo?.transferCharacteristics ?? ""))
        continue;
      const id = `v${format.itag}`;
      const codecs =
        family === "vp9"
          ? vp9Codecs(format.width, format.height, format.fps ?? 30)
          : parsed.codecs;
      video.push({
        ...base,
        codecs,
        id,
        kind: "video",
        mimeType: parsed.mimeType,
        family,
        width: format.width,
        height: format.height,
        fps: format.fps ?? 30,
      });
      media.set(id, { url: format.url, contentLength, itag: format.itag });
    } else {
      if (format.isDrc) continue;
      const id = audioId(format);
      if (media.has(id)) continue;
      audio.push({
        ...base,
        id,
        kind: "audio",
        mimeType: parsed.mimeType,
        sampleRate: Number(format.audioSampleRate) || 48_000,
        channels: format.audioChannels ?? 2,
        ...(format.audioTrack
          ? { language: format.audioTrack.id.split(".")[0] }
          : {}),
        label: format.audioTrack?.displayName ?? "Audio",
        isOriginal: format.audioTrack ? format.audioTrack.audioIsDefault : true,
      });
      media.set(id, { url: format.url, contentLength, itag: format.itag });
    }
  }
  const captions: PresentationSources["captions"] = new Map();
  const captionTracks: CaptionTrack[] = [];
  for (const [i, track] of (
    result.raw.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? []
  ).entries()) {
    const id = `c${i}-${track.languageCode.replace(/[^A-Za-z0-9-]/g, "")}`;
    const label =
      track.name?.simpleText ??
      track.name?.runs?.map((r) => r.text).join("") ??
      track.languageCode;
    captionTracks.push({
      id,
      language: track.languageCode,
      label,
      autoGenerated: track.kind === "asr",
    });
    captions.set(
      id,
      new URL(track.baseUrl, "https://www.youtube.com").toString(),
    );
  }
  const durationMs = Number(
    result.formats.find((f) => f.approxDurationMs)?.approxDurationMs,
  );
  const durationSec =
    durationMs > 0
      ? durationMs / 1000
      : Number(result.raw.videoDetails?.lengthSeconds) || 0;
  return {
    presentation: { durationSec, video, audio, captions: captionTracks },
    media,
    captions,
  };
}

type ParsedMime =
  | { kind: "video"; mimeType: VideoTrack["mimeType"]; codecs: string }
  | { kind: "audio"; mimeType: AudioTrack["mimeType"]; codecs: string };

function parseMime(mimeType: string): ParsedMime | null {
  const m = /^(video|audio)\/(mp4|webm);\s*codecs="([^"]+)"/.exec(mimeType);
  if (!m) return null;
  const container = m[2] as "mp4" | "webm";
  const codecs = m[3] as string;
  return m[1] === "video"
    ? { kind: "video", mimeType: `video/${container}`, codecs }
    : { kind: "audio", mimeType: `audio/${container}`, codecs };
}

/**
 * YouTube labels VP9 as just `vp9`, which capability checks reject as
 * ambiguous. Profile 0, 8-bit (HDR is filtered out), at the lowest level that
 * covers the picture size and frame rate: an inflated level makes some
 * hardware decoders refuse streams they could play.
 */
export function vp9Codecs(width: number, height: number, fps: number): string {
  const samples = width * height;
  const fast = fps > 30;
  const level =
    samples <= 36_864
      ? 10
      : samples <= 73_728
        ? 11
        : samples <= 122_880
          ? 20
          : samples <= 245_760
            ? 21
            : samples <= 552_960
              ? 30
              : samples <= 983_040
                ? 31
                : samples <= 2_228_224
                  ? fast
                    ? 41
                    : 40
                  : samples <= 8_912_896
                    ? fast
                      ? 51
                      : 50
                    : fast
                      ? 61
                      : 60;
  return `vp09.00.${level}.08`;
}

function familyOf(codecs: string): VideoFamily | null {
  if (codecs.startsWith("avc1")) return "avc";
  if (codecs.startsWith("vp9") || codecs.startsWith("vp09")) return "vp9";
  if (codecs.startsWith("av01")) return "av01";
  return null;
}

/** Dubbed tracks share itags, so the audio track id is part of a track's id. */
function audioId(format: RawFormat): string {
  const track = format.audioTrack?.id.replace(/[^A-Za-z0-9.-]/g, "");
  return track ? `a${format.itag}-${track}` : `a${format.itag}`;
}

function range(r: { start: string; end: string }): {
  start: number;
  end: number;
} {
  return { start: Number(r.start), end: Number(r.end) };
}
