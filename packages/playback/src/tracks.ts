/**
 * What a player is offered, independent of where it comes from: the tracks
 * of one video, each a single file read by byte ranges (`init` and `index`
 * locate its header and segment index).
 */
export interface ByteRange {
  start: number;
  /** Inclusive, as in HTTP ranges. */
  end: number;
}

export type VideoFamily = "avc" | "vp9" | "av01";

interface TrackBase {
  /** Stable within a presentation; used in URLs. */
  id: string;
  mimeType: "video/mp4" | "video/webm" | "audio/mp4" | "audio/webm";
  codecs: string;
  bitrate: number;
  contentLength: number;
  init: ByteRange;
  index: ByteRange;
}

export interface VideoTrack extends TrackBase {
  kind: "video";
  family: VideoFamily;
  width: number;
  height: number;
  fps: number;
}

export interface AudioTrack extends TrackBase {
  kind: "audio";
  sampleRate: number;
  channels: number;
  /** BCP 47 language, when YouTube names one. */
  language?: string;
  label: string;
  /** The original language: the one players should start with. */
  isOriginal: boolean;
}

export interface CaptionTrack {
  id: string;
  language: string;
  label: string;
  autoGenerated: boolean;
}

export interface Presentation {
  durationSec: number;
  video: VideoTrack[];
  audio: AudioTrack[];
  captions: CaptionTrack[];
}

/** Where a manifest points; the gateway supplies session-relative paths. */
export interface PresentationUrls {
  media(track: VideoTrack | AudioTrack): string;
  mediaPlaylist(track: VideoTrack | AudioTrack): string;
  caption(track: CaptionTrack): string;
  subtitlePlaylist(track: CaptionTrack): string;
}

export function rangeText(r: ByteRange): string {
  return `${r.start}-${r.end}`;
}
