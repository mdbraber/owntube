import type { ByteRange } from "../tracks.ts";
import { box, fullBox, Writer } from "./boxes.ts";
import type { Fragment, Sample, TrackInit } from "./fragmented.ts";

/**
 * A regular ("fast start") MP4 assembled from fragmented tracks without
 * copying media: the header (ftyp, moov with complete sample tables, the mdat
 * header) is generated, and the mdat body is the tracks' sample data, one
 * chunk per fragment, in time order. Every player can play and seek such a
 * file, which is what RSS enclosures need.
 */
export interface ProgressiveSource {
  /** Identifies where this track's bytes come from (a presentation track id). */
  source: string;
  init: TrackInit;
  fragments: Fragment[];
}

export interface ProgressiveFile {
  size: number;
  header: Uint8Array;
  /** The mdat body, in file order: each chunk is a range of one source's bytes. */
  chunks: Array<{ source: string; upstream: ByteRange; offset: number }>;
}

/** A piece of a requested span: generated bytes, or a range of a source's bytes. */
export type Part = { bytes: Uint8Array } | { source: string; range: ByteRange };

const MOVIE_TIMESCALE = 1000;

export function buildProgressive(
  tracks: readonly ProgressiveSource[],
): ProgressiveFile {
  // Chunks in time order, so a player reading the file front to back gets audio and video together.
  const order = tracks
    .flatMap((t, track) =>
      t.fragments.map((f, index) => ({
        track,
        index,
        at: f.decodeTime / t.init.timescale,
      })),
    )
    .sort((a, b) => a.at - b.at || a.track - b.track);
  const dataBytes = tracks.reduce(
    (n, t) =>
      n + t.fragments.reduce((m, f) => m + (f.data.end - f.data.start + 1), 0),
    0,
  );
  const large = dataBytes > 0xffff_0000;

  // Chunk offsets depend on the header's size, which does not depend on their values.
  const layout = (headerSize: number) => {
    let offset = headerSize;
    const chunkOffsets = tracks.map(() => [] as number[]);
    const chunks: ProgressiveFile["chunks"] = [];
    for (const { track, index } of order) {
      const t = tracks[track] as ProgressiveSource;
      const f = t.fragments[index] as Fragment;
      (chunkOffsets[track] as number[])[index] = offset;
      chunks.push({ source: t.source, upstream: f.data, offset });
      offset += f.data.end - f.data.start + 1;
    }
    return { chunkOffsets, chunks, size: offset };
  };
  const header = (offsets: number[][]) => {
    const ftyp = box(
      "ftyp",
      new Writer().ascii("isom").u32(0x200).ascii("isomiso2avc1mp41").done(),
    );
    const mdatHeader = large
      ? new Writer()
          .u32(1)
          .ascii("mdat")
          .u64(16 + dataBytes)
          .done()
      : new Writer()
          .u32(8 + dataBytes)
          .ascii("mdat")
          .done();
    return concat(ftyp, moov(tracks, offsets, large), mdatHeader);
  };
  const draft = header(tracks.map((t) => t.fragments.map(() => 0)));
  const { chunkOffsets, chunks, size } = layout(draft.byteLength);
  const final = header(chunkOffsets);
  if (final.byteLength !== draft.byteLength)
    throw new Error("mp4: header size changed with its offsets");
  return { size, header: final, chunks };
}

/** What makes up bytes `span` of the file. */
export function partsOf(file: ProgressiveFile, span: ByteRange): Part[] {
  const parts: Part[] = [];
  if (span.start < file.header.byteLength) {
    parts.push({
      bytes: file.header.subarray(
        span.start,
        Math.min(span.end + 1, file.header.byteLength),
      ),
    });
  }
  for (const chunk of file.chunks) {
    const length = chunk.upstream.end - chunk.upstream.start + 1;
    const from = Math.max(span.start, chunk.offset);
    const to = Math.min(span.end, chunk.offset + length - 1);
    if (from > to) continue;
    parts.push({
      source: chunk.source,
      range: {
        start: chunk.upstream.start + (from - chunk.offset),
        end: chunk.upstream.start + (to - chunk.offset),
      },
    });
  }
  return parts;
}

function moov(
  tracks: readonly ProgressiveSource[],
  chunkOffsets: number[][],
  large: boolean,
): Uint8Array {
  const durations = tracks.map((t) => {
    const media = t.fragments.reduce(
      (n, f) => n + f.samples.reduce((m, s) => m + s.duration, 0),
      0,
    );
    const lead = (t.fragments[0]?.decodeTime ?? 0) / t.init.timescale;
    return {
      media,
      movie: Math.round((media / t.init.timescale + lead) * MOVIE_TIMESCALE),
      lead,
    };
  });
  const movieDuration = Math.max(...durations.map((d) => d.movie));
  const mvhd = fullBox(
    "mvhd",
    0,
    0,
    new Writer()
      .u32(0)
      .u32(0)
      .u32(MOVIE_TIMESCALE)
      .u32(movieDuration)
      .u32(0x0001_0000) // rate 1.0
      .u16(0x0100) // volume 1.0
      .zeros(10)
      .bytes(MATRIX)
      .zeros(24)
      .u32(tracks.length + 1) // next_track_ID
      .done(),
  );
  const traks = tracks.map((t, i) =>
    trak(
      t,
      i + 1,
      durations[i] as { media: number; movie: number; lead: number },
      chunkOffsets[i] as number[],
      large,
    ),
  );
  return box("moov", mvhd, ...traks);
}

function trak(
  t: ProgressiveSource,
  trackId: number,
  d: { media: number; movie: number; lead: number },
  chunkOffsets: number[],
  large: boolean,
): Uint8Array {
  const audio = t.init.kind === "audio";
  const tkhd = fullBox(
    "tkhd",
    0,
    0x3, // enabled, in movie
    new Writer()
      .u32(0)
      .u32(0)
      .u32(trackId)
      .u32(0)
      .u32(d.movie)
      .zeros(8)
      .u16(0) // layer
      .u16(0) // alternate group
      .u16(audio ? 0x0100 : 0)
      .u16(0)
      .bytes(MATRIX)
      .u32(audio ? 0 : t.init.width)
      .u32(audio ? 0 : t.init.height)
      .done(),
  );
  const mdhd = fullBox(
    "mdhd",
    0,
    0,
    new Writer()
      .u32(0)
      .u32(0)
      .u32(t.init.timescale)
      .u32(d.media)
      .u16(t.init.language)
      .u16(0)
      .done(),
  );
  const stbl = box(
    "stbl",
    t.init.stsd,
    ...sampleTables(t.fragments, chunkOffsets, !audio, large),
  );
  const minf = box("minf", t.init.mediaHeader, t.init.dinf, stbl);
  const mdia = box("mdia", mdhd, t.init.hdlr, minf);
  const edits = editList(t, d.lead);
  return box("trak", tkhd, ...(edits ? [edits] : []), mdia);
}

/** The source's edit list, with an empty edit first when the track starts late. */
function editList(
  t: ProgressiveSource,
  leadSec: number,
): Uint8Array | undefined {
  const entries = [...t.init.edits];
  if (leadSec > 0) entries.unshift({ durationSec: leadSec, mediaTime: -1 });
  if (entries.length === 0) return undefined;
  const w = new Writer().u32(entries.length);
  for (const e of entries)
    w.u32(Math.round(e.durationSec * MOVIE_TIMESCALE))
      .i32(e.mediaTime)
      .u16(1)
      .u16(0);
  return box("edts", fullBox("elst", 0, 0, w.done()));
}

function sampleTables(
  fragments: readonly Fragment[],
  chunkOffsets: number[],
  video: boolean,
  large: boolean,
): Uint8Array[] {
  const samples: Sample[] = fragments.flatMap((f) => f.samples);

  const stts = runs(samples.map((s) => s.duration));
  const sttsBox = fullBox("stts", 0, 0, table(stts.length, stts.flat()));

  const out = [sttsBox];
  if (samples.some((s) => s.cto !== 0)) {
    const ctts = runs(samples.map((s) => s.cto));
    const signed = samples.some((s) => s.cto < 0);
    const w = new Writer().u32(ctts.length);
    for (const [count, value] of ctts) {
      w.u32(count);
      if (signed) w.i32(value);
      else w.u32(value);
    }
    out.push(fullBox("ctts", signed ? 1 : 0, 0, w.done()));
  }
  if (video && samples.some((s) => !s.sync)) {
    const sync = samples.flatMap((s, i) => (s.sync ? [i + 1] : []));
    out.push(fullBox("stss", 0, 0, table(sync.length, sync)));
  }
  const perChunk = runs(fragments.map((f) => f.samples.length));
  const stsc: number[] = [];
  let firstChunk = 1;
  for (const [count, samplesPerChunk] of perChunk) {
    stsc.push(firstChunk, samplesPerChunk, 1);
    firstChunk += count;
  }
  out.push(fullBox("stsc", 0, 0, table(perChunk.length, stsc)));
  out.push(
    fullBox(
      "stsz",
      0,
      0,
      table(
        samples.length,
        samples.map((s) => s.size),
        0,
      ),
    ),
  );
  if (large) {
    const w = new Writer().u32(chunkOffsets.length);
    for (const o of chunkOffsets) w.u64(o);
    out.push(fullBox("co64", 0, 0, w.done()));
  } else {
    out.push(fullBox("stco", 0, 0, table(chunkOffsets.length, chunkOffsets)));
  }
  return out;
}

/** `count` followed by the values, all u32; `prefix` values come before the count. */
function table(
  count: number,
  values: readonly number[],
  ...prefix: number[]
): Uint8Array {
  const w = new Writer();
  for (const p of prefix) w.u32(p);
  w.u32(count);
  for (const v of values) w.u32(v);
  return w.done();
}

/** Run-length encoding: [count, value] pairs. */
function runs(values: readonly number[]): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  for (const v of values) {
    const last = out[out.length - 1];
    if (last && last[1] === v) last[0]++;
    else out.push([1, v]);
  }
  return out;
}

function concat(...parts: Uint8Array[]): Uint8Array {
  const w = new Writer();
  for (const p of parts) w.bytes(p);
  return w.done();
}

// Unity transformation matrix.
const MATRIX = new Writer()
  .u32(0x0001_0000)
  .u32(0)
  .u32(0)
  .u32(0)
  .u32(0x0001_0000)
  .u32(0)
  .u32(0)
  .u32(0)
  .u32(0x4000_0000)
  .done();
