import { describe, expect, it } from "vitest";
import { buildMpd } from "./dash.ts";
import {
  buildMasterPlaylist,
  buildMediaPlaylist,
  buildSubtitlePlaylist,
} from "./hls.ts";
import type {
  AudioTrack,
  Presentation,
  PresentationUrls,
  VideoTrack,
} from "./tracks.ts";

const video = (
  itag: number,
  height: number,
  family: VideoTrack["family"] = "avc",
): VideoTrack => ({
  id: `v${itag}`,
  kind: "video",
  mimeType: family === "vp9" ? "video/webm" : "video/mp4",
  family,
  codecs: family === "vp9" ? "vp9" : "avc1.640028",
  bitrate: height * 1000,
  contentLength: 1_000_000,
  init: { start: 0, end: 740 },
  index: { start: 741, end: 1500 },
  width: Math.round((height * 16) / 9),
  height,
  fps: 30,
});

const audio = (
  language: string,
  isOriginal: boolean,
  bitrate = 128_000,
): AudioTrack => ({
  id: `a140-${language}`,
  kind: "audio",
  mimeType: "audio/mp4",
  codecs: "mp4a.40.2",
  bitrate,
  contentLength: 500_000,
  init: { start: 0, end: 631 },
  index: { start: 632, end: 1000 },
  sampleRate: 44_100,
  channels: 2,
  language,
  label: language === "nl" ? "Dutch original" : "English",
  isOriginal,
});

const presentation: Presentation = {
  durationSec: 212.5,
  video: [video(137, 1080), video(136, 720), video(248, 1080, "vp9")],
  audio: [audio("en", false), audio("nl", true)],
  captions: [
    { id: "c0-nl", language: "nl", label: "Dutch", autoGenerated: false },
  ],
};

const urls: PresentationUrls = {
  media: (t) => `t/${t.id}`,
  mediaPlaylist: (t) => `p/${t.id}.m3u8`,
  caption: (c) => `c/${c.id}.vtt`,
  subtitlePlaylist: (c) => `c/${c.id}.m3u8`,
};

describe("buildMpd", () => {
  const mpd = buildMpd(presentation, urls);

  it("is a static on-demand MPD with the duration", () => {
    expect(mpd).toContain('type="static"');
    expect(mpd).toContain('mediaPresentationDuration="PT212.500S"');
  });

  it("reads every representation by byte range from its own file", () => {
    expect(mpd).toContain("<BaseURL>t/v137</BaseURL>");
    expect(mpd).toContain('<SegmentBase indexRange="741-1500">');
    expect(mpd).toContain('<Initialization range="0-740"/>');
  });

  it("keeps codecs families in separate adaptation sets", () => {
    expect(mpd.match(/contentType="video"/g)).toHaveLength(2);
  });

  it("marks the original audio main and the others dub", () => {
    expect(mpd).toMatch(/lang="nl"[^>]*>\s*<Role[^>]*value="main"/);
    expect(mpd).toMatch(/lang="en"[^>]*>\s*<Role[^>]*value="dub"/);
  });

  it("escapes text", () => {
    const tricky = buildMpd(
      {
        ...presentation,
        captions: [
          { id: "c1", language: "en", label: 'A & "B"', autoGenerated: true },
        ],
      },
      urls,
    );
    expect(tricky).toContain("<Label>A &#38; &#34;B&#34;</Label>");
  });
});

describe("buildMasterPlaylist", () => {
  const master = buildMasterPlaylist(presentation, urls);

  it("offers only MP4 video, best first", () => {
    const variants = master.split("\n").filter((l) => l.startsWith("p/v"));
    expect(variants).toEqual(["p/v137.m3u8", "p/v136.m3u8"]);
  });

  it("makes only the original audio the default and auto-selectable", () => {
    expect(master).toMatch(
      /NAME="Dutch original",LANGUAGE="nl",DEFAULT=YES,AUTOSELECT=YES/,
    );
    expect(master).toMatch(
      /NAME="English",LANGUAGE="en",DEFAULT=NO,AUTOSELECT=NO/,
    );
  });

  it("links subtitles to every variant", () => {
    expect(master).toContain('TYPE=SUBTITLES,GROUP-ID="subs"');
    expect(master).toMatch(/AUDIO="audio",SUBTITLES="subs"/);
  });
});

describe("buildMediaPlaylist", () => {
  const playlist = buildMediaPlaylist(
    video(137, 1080),
    [
      { range: { start: 1501, end: 2500 }, durationSec: 5.005 },
      { range: { start: 2501, end: 4000 }, durationSec: 4.2 },
    ],
    urls,
  );

  it("maps the init section and lists each segment as a byte range", () => {
    expect(playlist).toContain('#EXT-X-MAP:URI="t/v137",BYTERANGE="741@0"');
    expect(playlist).toContain("#EXT-X-BYTERANGE:1000@1501");
    expect(playlist).toContain("#EXT-X-BYTERANGE:1500@2501");
    expect(playlist).toContain("#EXT-X-TARGETDURATION:6");
    expect(playlist.trimEnd().endsWith("#EXT-X-ENDLIST")).toBe(true);
  });
});

describe("buildSubtitlePlaylist", () => {
  it("is one VTT file for the whole video", () => {
    const playlist = buildSubtitlePlaylist(
      presentation.captions[0] as never,
      212.5,
      urls,
    );
    expect(playlist).toContain("#EXTINF:212.500,\nc/c0-nl.vtt");
  });
});
